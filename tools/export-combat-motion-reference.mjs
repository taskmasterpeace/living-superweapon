import {writeFile} from 'node:fs/promises';
import {STRIKES} from '../src/data/martial.js';
import {ACTION_DRAFTS} from '../src/engine/character-action-drafts.js';

// Regenerate from the same definitions consumed by gameplay and the editor.
const runtime=Object.entries(STRIKES).map(([id,s])=>({id,name:s.n,
 status:'gameplay',startup:s.startup,active:s.active,recovery:s.recover,
 controlReturn:Number((s.startup+s.active+s.recover).toFixed(4)),
 baseDamage:s.dmg,reachWorldUnits:s.reach,cancels:s.cancels}));
const candidates=Object.entries(ACTION_DRAFTS).map(([name,d])=>({name,
 status:d.visualReview?.rejected?'rejected':'candidate',duration:d.duration,
 loop:!!d.loop,hand:d.hand||null,contactStyle:d.contactStyle||null,
 markers:d.markers||{contact:d.contact??null,release:d.release??null,controlReturn:d.controlReturn??null},
 visualReview:d.visualReview||null,
 editorUrl:`/character-foundation.html?study=${encodeURIComponent(name)}`}));
const reference={schemaVersion:1,units:'seconds unless otherwise named',
 caveats:[
  'Runtime timings are baseline at meleePace=1. Character pace scales phase durations.',
  'A travelling melee approach can extend startup. Hitstop pauses the phase clock; interrupts and legal cancels can end commitment early.',
  'Base damage is definition data, not final HP loss; momentum, rank, defenses and attack-specific resolution still apply.',
  'Candidate markers do not create hitboxes, release a projectile, or grant control in gameplay.',
  'Looping studies have no automatic gameplay control-return time. Rejected studies remain blocked from assignment.',
  'Two-person rescue is excluded. Pickup and grab studies target one other person or one object.'
 ],runtime,candidates};
const f=v=>v==null?'—':Number(v).toFixed(3);
const md=['# Power World combat motion reference','',
 'Generated by `node tools/export-combat-motion-reference.mjs`. Edit source definitions, then regenerate; do not tune the generated tables directly.','',
 ...reference.caveats.map(s=>`- ${s}`),'','## Live melee phases','',
 '| Move | Startup | Active | Recovery | Normal control return | Base damage |',
 '|---|---:|---:|---:|---:|---:|',
 ...runtime.map(s=>`| ${s.name} | ${f(s.startup)} | ${f(s.active)} | ${f(s.recovery)} | ${f(s.controlReturn)} | ${s.baseDamage} |`),
 '','## Studio studies — not gameplay assignments','',
 '| Study | Status | Duration | Contact | Release | Control marker |',
 '|---|---|---:|---:|---:|---:|',
 ...candidates.map(s=>`| ${s.name} | ${s.status}${s.loop?' · loop':''} | ${f(s.duration)} | ${f(s.markers.contact)} | ${f(s.markers.release)} | ${s.loop?'—':f(s.markers.controlReturn)} |`),
 '','Review candidates through the character studio. A timing marker is an authoring proposal until the corresponding gameplay action consumes it.',''];
await writeFile(new URL('../docs/combat-motion-reference.json',import.meta.url),JSON.stringify(reference,null,2)+'\n');
await writeFile(new URL('../docs/COMBAT_MOTION_REFERENCE.md',import.meta.url),md.join('\n'));
console.log(`Exported ${runtime.length} gameplay moves and ${candidates.length} studio studies.`);
