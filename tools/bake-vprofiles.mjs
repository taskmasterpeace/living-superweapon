// BAKE THE VISUAL-PROFILE DIFFERENTIATION — run offline, commit the result.
//
// "Every ability gets a 7-trait profile, no two sharing >3 traits" is a mixed-alphabet distance-4
// coding problem (docs + issue #13). Its solver (differentiateProfiles, min-conflicts) takes tens of
// seconds — far too slow to run at game boot — so we run it ONCE here and bake the per-ability
// overrides into src/data/vprofiles.generated.js, which applyProfiles() loads instantly at boot.
//
// ⚠ TRUE ZERO IS PROVEN IMPOSSIBLE for this roster: `physical|none` and `elemental|stun` each hold
// 69 abilities that share family AND status-read, but a distance-4 code over the five free axes tops
// out near 50 codewords. The residual printed below is the roster's mathematical FLOOR, not a bug —
// it is the count of abilities that are honestly too alike to separate without lying about what they
// are. Re-run this after ANY change to the profile derivation or the roster.
//
//   node tools/bake-vprofiles.mjs
import { writeFileSync } from 'fs';
import { differentiateProfiles, verifyProfiles, profileOf } from '../src/data/visual.js';
import * as cx from '../src/data/characters.js';

const ROSTER = cx.ROSTER || cx.default || cx.CHARACTERS;
const SWEEPS = Number(process.argv[2] || 600);

console.error(`[bake] solving with ${SWEEPS} sweeps over ${ROSTER.length} fighters…`);
const t0 = Date.now();
differentiateProfiles(ROSTER, { sweeps: SWEEPS, log: (s) => console.error(s) });
const secs = ((Date.now() - t0) / 1000).toFixed(1);

const map = {};
for (const def of ROSTER) for (const key of Object.keys(def.abilities || {})) {
  const ov = def.abilities[key]._vauto;
  if (ov && Object.keys(ov).length) map[`${def.id}.${key}`] = ov;
}
const residual = verifyProfiles(ROSTER).failures;
const pairs = verifyProfiles(ROSTER).checks;

const body = `// GENERATED by tools/bake-vprofiles.mjs — DO NOT EDIT BY HAND.
// The deterministic differentiation of every ability's 7-trait visual profile so no two share >3.
// Residual collisions: ${residual} of ${pairs} pairs (${(100 - residual / pairs * 100).toFixed(2)}% distinct) — the roster's
// mathematical floor (see the tool header / issue #13). Re-bake after any derivation or roster change.
export const VPROFILES = ${JSON.stringify(map)};
`;
writeFileSync('src/data/vprofiles.generated.js', body);
console.error(`[bake] wrote src/data/vprofiles.generated.js — ${Object.keys(map).length} overrides, residual ${residual}/${pairs} in ${secs}s`);
